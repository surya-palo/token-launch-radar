// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// early radar: every pre-token protocol below the watchlist floor that passes the house's own
// exclusion rule (not a wrapped, staked or bridged product of a token that already trades). A
// protocol is pre-token when its record carries no token (no market cap, no CoinGecko id, no
// symbol); the live-token protocols are kept apart and shown with the market's own values, never
// mixed into the ranked board. The big wrapped and staked products above the floor (WBTC, Binance
// staked ETH, USDT0 and the exchanges) are set aside with the reason each one was left out.
//
// Implied value follows only from the snapshot's own figures, and its one market input is measured
// on the snapshot itself:
//
//   multiple   = the category's median mcap/TVL among the snapshot's live-token protocols,
//                shrunk toward the global median and clamped to [0.02, 1.5]; a category with
//                fewer than 3 live protocols uses the global median
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.65 + min(age_days, 1460) / 1460 x 0.35   (age_days unknown: 365)
//   breadth    = 1 + 0.05 x min(chains - 1, 4)
//   implied    = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the category
// multiples are computed from the snapshot at run time, so the model re-calibrates itself on any
// snapshot it is given.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

